#!/usr/bin/env python3
# Prompt-based report: summarises the monitoring log and detects issues
import os, json, subprocess, urllib.request

LOG_FILE = "exp1/system_monitor.log"
REPORT = "exp4/report.md"
MODELS = ["gemini-3.1-flash-lite", "gemini-3.5-flash-lite", "gemini-2.5-flash"]

# 1. Read the data (log tail, or live values if the log is empty)
data = ""
if os.path.exists(LOG_FILE):
    data = open(LOG_FILE).read()[-1500:]
if data.strip() == "":
    data = subprocess.getoutput("date; df -h /; free -h")

# 2. Build the prompt
prompt = ("You are a DevOps assistant. Read this system monitoring log and write a short report "
          "with exactly two sections:\n"
          "## Summary - one paragraph on overall system health.\n"
          "## Issues Detected - bullet list of errors or resource problems "
          "(disk above 80%, high memory, no swap). If none, write 'No issues detected.'\n\n"
          "Log:\n" + data)

# 3. Ask Gemini (try each model in turn)
key = os.environ.get("GEMINI_API_KEY", "")
answer = None
for model in MODELS:
    if key == "":
        break
    try:
        url = "https://generativelanguage.googleapis.com/v1beta/models/" + model + ":generateContent"
        body = json.dumps({"contents": [{"parts": [{"text": prompt}]}]}).encode()
        req = urllib.request.Request(url, data=body, headers={"Content-Type": "application/json", "x-goog-api-key": key})
        result = json.loads(urllib.request.urlopen(req, timeout=60).read())
        answer = result["candidates"][0]["content"]["parts"][0]["text"]
        print("Report generated by", model)
        break
    except Exception as e:
        print(model, "failed:", e)

# 4. Fallback if the AI is not reachable
if answer is None:
    answer = "## Summary\nAI not reachable, rule-based check used.\n\n## Issues Detected\n"
    found = False
    for word in data.split():
        if word.endswith("%") and word[:-1].isdigit() and int(word[:-1]) >= 80:
            answer += "- Disk usage is high: " + word + "\n"
            found = True
            break
    if not found:
        answer += "- No issues detected.\n"

# 5. Save the report
with open(REPORT, "w") as f:
    f.write("# Automated System Report\n\n" + answer + "\n")
print(open(REPORT).read())
